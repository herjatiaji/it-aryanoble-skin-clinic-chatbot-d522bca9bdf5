def upload_image(content: bytes, filename: str, content_type: str = "image/png") -> dict:
    """
    Synchronously uploads image binary content to images bucket (PUBLIC-READ).
    Falls back cleanly to local disk storage ONLY if MinIO is unavailable.
    """
    clean_filename = re.sub(r'[^a-zA-Z0-9._-]', '_', str(filename or "image.png"))
    clean_filename = re.sub(r'_+', '_', clean_filename)
    s3_key = f"images/{uuid.uuid4().hex}_{clean_filename}"
    browser_url = _format_browser_url(None, s3_key)
    bucket_name = _images_bucket()

    client = _get_client()
    if not client:
        _save_file_to_local_disk(content, filename, s3_key=s3_key)
        return {
            "s3_key": s3_key,
            "image_url": browser_url,
            "size": len(content),
            "status": "fallback"
        }

    try:
        extra_args = {}
        if content_type:
            extra_args["ContentType"] = content_type

        client.put_object(
            Bucket=bucket_name,
            Key=s3_key,
            Body=content,
            **extra_args
        )

        logger.debug(f"✅ Successfully uploaded image '{filename}' to MinIO -> {browser_url}")
        return {
            "s3_key": s3_key,
            "image_url": browser_url,
            "size": len(content),
            "status": "success"
        }
    except Exception as e:
        logger.warning(f"MinIO upload error for '{filename}': {e}. Falling back to local disk.")
        _save_file_to_local_disk(content, filename, s3_key=s3_key)
        return {
            "s3_key": s3_key,
            "image_url": browser_url,
            "size": len(content),
            "status": "fallback"
        }


def upload_images_parallel(images: list) -> list:
    """
    Upload multiple images to MinIO concurrently using ThreadPoolExecutor.
    Falls back cleanly to local disk storage ONLY if MinIO is offline.
    """
    if not images:
        return []

    client = _get_client()
    bucket_name = _images_bucket() if client else None

    if not client:
        results = []
        for img in images:
            s3_key = f"images/{uuid.uuid4().hex}_{img['filename']}"
            if img.get("content") and img.get("filename"):
                _save_file_to_local_disk(img["content"], img["filename"], s3_key=s3_key)
            results.append({
                "s3_key": s3_key,
                "image_url": _format_browser_url(None, s3_key),
                "size": len(img.get("content", b"")),
                "status": "fallback"
            })
        return results

    def _upload_single(img_data: dict) -> dict:
        fname = img_data["filename"]
        content = img_data["content"]
        ctype = img_data.get("content_type", "image/png")
        s3_key = f"images/{uuid.uuid4().hex}_{fname}"
        browser_url = _format_browser_url(None, s3_key)
        try:
            extra_args = {}
            if ctype:
                extra_args["ContentType"] = ctype
            client.put_object(
                Bucket=bucket_name,
                Key=s3_key,
                Body=content,
                **extra_args
            )
            logger.debug(f"Uploaded '{fname}' to MinIO -> {browser_url}")
            return {
                "s3_key": s3_key,
                "image_url": browser_url,
                "size": len(content),
                "status": "success"
            }
        except Exception as e:
            logger.warning(f"MinIO upload failed for '{fname}': {e}. Falling back to local disk.")
            _save_file_to_local_disk(content, fname, s3_key=s3_key)
            return {
                "s3_key": s3_key,
                "image_url": browser_url,
                "size": len(content),
                "status": "fallback"
            }

    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=min(len(images), 8)) as executor:
        results = list(executor.map(_upload_single, images))

    success_count = sum(1 for r in results if r["status"] == "success")
    logger.info(f"Parallel upload complete: {success_count}/{len(images)} images uploaded successfully.")
    return results


